# Pesquisa de Satisfação - TudoWeb

print("PESQUISA DE SATISFAÇÃO - TUDOWEB")

excelente = 0
ruim = 0

# Pesquisa oficial com 50 entrevistados
quantidade = 50

for i in range(quantidade):
    print(f"\nEntrevistado {i + 1}")

    nome = input("Digite seu nome: ")
    idade = int(input("Digite sua idade: "))

    print("Como você avalia nosso atendimento?")
    print("1 - EXCELENTE")
    print("2 - BOM")
    print("3 - RUIM")

    opiniao = int(input("Digite sua opinião (1, 2 ou 3): "))

    while opiniao not in (1, 2, 3):
        print("Opção inválida!")
        opiniao = int(input("Digite 1, 2 ou 3: "))

    if opiniao == 1:
        excelente += 1
        avaliacao = "EXCELENTE"
    elif opiniao == 2:
        avaliacao = "BOM"
    else:
        ruim += 1
        avaliacao = "RUIM"

    print(f"Obrigado, {nome}! Avaliação: {avaliacao}")

print("\n===== RESULTADO DA PESQUISA =====")
print(f"Total de entrevistados: {quantidade}")
print(f"Respostas EXCELENTE: {excelente}")
print(f"Respostas RUIM: {ruim}")
print("Pesquisa finalizada!")